/** What every archetype must produce, so four incomparable methods can share one map. */
export type ScenarioResult = {
  scenarioId: string;
  account: string;
  archetype: Archetype;
  modelKey: string;
  modelLabel: string;

  /**
   * The single number a founder compares across accounts: rupees of business
   * value per month, net of every cost the system introduces. It is the ONLY
   * quantity that means the same thing in all four archetypes, which is why the
   * map is denominated in it rather than in accuracy.
   */
  valueInrPerMonth: number;
  baselineInrPerMonth: number;

  /** Archetype-native headline. Deliberately NOT comparable across archetypes. */
  headline: { label: string; value: string; sub?: string };

  /** Whatever this archetype's method produces, for its own panel. */
  detail: Record<string, unknown>;

  /** Honest limits specific to this evaluation, surfaced on the page. */
  caveats: string[];

  costUsd: number;
  attempts: number;
};

export type Scenario = {
  id: string;
  account: string;
  accountNote: string;
  archetype: Archetype;
  title: string;
  /** The problem as the company would state it. */
  brief: string;
  /** Why the standard toolkit does or does not apply here. */
  whyThisMethod: string;
  /** Monthly volume of decisions, and what one decision is worth. */
  scale: { volume: number; valuePerDecisionInr: number };
  run: (adapter: Adapter, opts: RunOpts) => Promise<ScenarioResult>;
};

export type RunOpts = {
  n: number;
  seed: number;
  cacheDir: string;
  maxUsd: number;
  onProgress?: (done: number, total: number) => void;
};

