/**
 * SCENARIOS — the unit of this bench, and the whole argument in one file.
 *
 * A benchmark assumes one shape: an item, an answer, a label, a score. That
 * shape fits exactly one of the four business archetypes below, and applying it
 * to the other three does not produce a worse number. It produces a confident
 * number about the wrong quantity.
 *
 *   A · VOLUME GRIND        Meesho catalogue enrichment
 *       Unit of evaluation: THE ITEM.
 *       Millions of cheap decisions. Cost per resolved unit is the game, and
 *       item-level grading works exactly as advertised.
 *
 *   B · HIGH-STAKES CALL    Aye Finance MSME underwriting
 *       Unit of evaluation: THE COHORT.
 *       You never learn whether one decision was right. You learn, eighteen
 *       months later, what a portfolio of them did. So there is no per-item
 *       label to grade against and accuracy is not the objective: expected
 *       profit per application is, and it is driven by an asymmetry where one
 *       bad approval costs the principal and one bad decline costs the margin.
 *
 *   C · NO GROUND TRUTH     Spinny used-car pricing
 *       Unit of evaluation: THE POLICY.
 *       There is no correct price. There is only what happened at the price you
 *       chose, and you cannot observe what would have happened at any other.
 *       Worse: your history was generated by your OLD policy, so a naive replay
 *       of a new one is biased by the very thing you are trying to change. This
 *       needs off-policy evaluation, not grading.
 *
 *   D · ADVERSARIAL/ACTING  Cred collections
 *       Unit of evaluation: THE TRAJECTORY.
 *       The counterparty responds to what you did, so every action changes the
 *       distribution of the next state. A static test set is a photograph of a
 *       conversation that never happened.
 *
 * Each archetype therefore ships its own evaluator. They share cost accounting,
 * statistics and reporting, and share nothing about what "correct" means.
 */

